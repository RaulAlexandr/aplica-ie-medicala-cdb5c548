"""T11 local protected storage and content validation.

The storage root is configured with ``DOCUMENT_STORAGE_DIR``. Files are written as
``<root>/<clinic_id>/<key[:2]>/<key>`` where ``key`` is 32 random hex characters generated by the
server. The client filename never becomes part of a path. Nothing here is served statically: the
API streams content only after authorization.
"""

from __future__ import annotations

import hashlib
import os
import re
import secrets
import struct
import unicodedata
from collections.abc import AsyncIterator
from dataclasses import dataclass
from pathlib import Path
from uuid import UUID

from app.config import settings

REPO_ROOT = Path(__file__).resolve().parents[3]
KEY_PATTERN = re.compile(r"^[0-9a-f]{32}$")
INCOMING_DIR = ".incoming"
TYPE_EXTENSIONS = {
    "image/jpeg": {".jpg", ".jpeg"},
    "image/png": {".png"},
    "application/pdf": {".pdf"},
}
IMAGE_TYPES = {"image/jpeg", "image/png"}
# Heuristic only: names that make a PDF interactive/active. Not an antivirus scan.
PDF_ACTIVE = re.compile(
    rb"/(JavaScript|JS|Launch|EmbeddedFiles?|RichMedia|XFA|SubmitForm|ImportData|GoToE)(?![A-Za-z0-9])"
)
PDF_HEX_ESCAPE = re.compile(rb"#([0-9A-Fa-f]{2})")


class StorageUnavailable(Exception):
    """Storage is not configured or not usable (HTTP 503)."""


class ContentRejected(Exception):
    def __init__(self, status_code: int, detail: str):
        super().__init__(detail)
        self.status_code = status_code
        self.detail = detail


@dataclass
class StagedFile:
    path: Path
    size: int
    sha256: str
    content_type: str = ""
    width: int | None = None
    height: int | None = None


def storage_root() -> Path:
    raw = settings.document_storage_dir
    if not raw:
        raise StorageUnavailable("Document storage is not configured")
    root = Path(raw)
    if not root.is_absolute():
        raise StorageUnavailable("Document storage must be an absolute path")
    root = root.resolve()
    if root == REPO_ROOT or REPO_ROOT in root.parents:
        raise StorageUnavailable("Document storage must be outside the repository")
    try:
        root.mkdir(mode=0o700, parents=True, exist_ok=True)
        (root / INCOMING_DIR).mkdir(mode=0o700, exist_ok=True)
    except OSError as exc:
        raise StorageUnavailable("Document storage is not writable") from exc
    return root


def safe_display_name(raw: str | None) -> str:
    """Display-only filename: last path component, NFC, no control/bidi characters, ≤200 chars."""
    value = unicodedata.normalize("NFC", raw or "")
    value = re.split(r"[/\\]", value)[-1]
    value = "".join(ch for ch in value if unicodedata.category(ch)[0] != "C")
    value = value.strip().strip(".").strip()
    if len(value) > 200:
        stem, dot, ext = value.rpartition(".")
        value = (stem[: 200 - len(ext) - 1] + "." + ext) if dot and len(ext) <= 10 else value[:200]
    return value or "document"


def extension_of(name: str) -> str:
    _, dot, ext = name.rpartition(".")
    return f".{ext.lower()}" if dot else ""


async def stage_upload(chunks: AsyncIterator[bytes], max_bytes: int) -> StagedFile:
    """Stream the request body to a private temp file, enforcing the size limit while reading."""
    root = storage_root()
    path = root / INCOMING_DIR / f"{secrets.token_hex(16)}.part"
    digest = hashlib.sha256()
    size = 0
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    try:
        with os.fdopen(fd, "wb") as handle:
            async for chunk in chunks:
                if not chunk:
                    continue
                size += len(chunk)
                if size > max_bytes:
                    raise ContentRejected(413, f"File exceeds the {max_bytes // (1024 * 1024)} MiB limit")
                digest.update(chunk)
                handle.write(chunk)
            handle.flush()
            os.fsync(handle.fileno())
    except BaseException:
        discard(path)
        raise
    if size == 0:
        discard(path)
        raise ContentRejected(422, "Empty file")
    return StagedFile(path=path, size=size, sha256=digest.hexdigest())


def discard(path: Path | None) -> None:
    if path is None:
        return
    try:
        path.unlink()
    except FileNotFoundError:
        pass


def inspect_content(staged: StagedFile) -> None:
    """Detect the real type from the bytes and enforce image/PDF rules. Raises ContentRejected."""
    with staged.path.open("rb") as handle:
        head = handle.read(16)
        if head.startswith(b"\x89PNG\r\n\x1a\n"):
            staged.content_type = "image/png"
            staged.width, staged.height = _png_size(handle)
        elif head.startswith(b"\xff\xd8\xff"):
            staged.content_type = "image/jpeg"
            staged.width, staged.height = _jpeg_size(handle)
        elif head.startswith(b"%PDF-"):
            staged.content_type = "application/pdf"
            _check_pdf(handle, staged.size)
        else:
            raise ContentRejected(415, "Unsupported file type: only JPEG, PNG and PDF are accepted")
    if staged.content_type in IMAGE_TYPES:
        width, height = staged.width or 0, staged.height or 0
        if width < 1 or height < 1:
            raise ContentRejected(415, "Image dimensions could not be read")
        side = settings.document_max_image_side
        if width > side or height > side or width * height > settings.document_max_image_pixels:
            raise ContentRejected(413, f"Image dimensions {width}×{height} exceed the configured limit")


def _png_size(handle) -> tuple[int, int]:
    handle.seek(8)
    header = handle.read(8 + 13)
    if len(header) < 21 or header[4:8] != b"IHDR":
        raise ContentRejected(415, "Invalid PNG header")
    width, height = struct.unpack(">II", header[8:16])
    handle.seek(-12, os.SEEK_END)
    if handle.read(12)[4:8] != b"IEND":
        raise ContentRejected(415, "Truncated or invalid PNG")
    return width, height


def _jpeg_size(handle) -> tuple[int, int]:
    handle.seek(2)
    while True:
        byte = handle.read(1)
        if not byte:
            break
        if byte != b"\xff":
            raise ContentRejected(415, "Invalid JPEG structure")
        marker = handle.read(1)
        while marker == b"\xff":
            marker = handle.read(1)
        if not marker:
            break
        code = marker[0]
        if code in (0xD8, 0x01) or 0xD0 <= code <= 0xD7:
            continue
        if code in (0xD9, 0xDA):
            break
        raw_length = handle.read(2)
        if len(raw_length) < 2:
            break
        length = struct.unpack(">H", raw_length)[0]
        if length < 2:
            raise ContentRejected(415, "Invalid JPEG segment")
        if 0xC0 <= code <= 0xCF and code not in (0xC4, 0xC8, 0xCC):
            data = handle.read(5)
            if len(data) < 5:
                break
            height, width = struct.unpack(">HH", data[1:5])
            return width, height
        handle.seek(length - 2, os.SEEK_CUR)
    raise ContentRejected(415, "JPEG dimensions could not be read")


def _check_pdf(handle, size: int) -> None:
    handle.seek(max(0, size - 2048))
    if b"%%EOF" not in handle.read():
        raise ContentRejected(415, "Truncated or invalid PDF")
    handle.seek(0)
    tail = b""
    while chunk := handle.read(1024 * 1024):
        window = tail + chunk
        decoded = PDF_HEX_ESCAPE.sub(lambda match: bytes([int(match.group(1), 16)]), window)
        if PDF_ACTIVE.search(window) or PDF_ACTIVE.search(decoded):
            raise ContentRejected(415, "PDF with active or embedded content is not accepted")
        tail = window[-64:]


def check_extension(display_name: str, content_type: str) -> None:
    if extension_of(display_name) not in TYPE_EXTENSIONS[content_type]:
        raise ContentRejected(415, "File extension does not match the file content")


def new_storage_key() -> str:
    return secrets.token_hex(16)


def content_path(clinic_id: UUID, key: str) -> Path:
    if not KEY_PATTERN.fullmatch(key):
        raise StorageUnavailable("Invalid storage key")
    return storage_root() / str(clinic_id) / key[:2] / key


def place(staged: StagedFile, clinic_id: UUID, key: str) -> Path:
    """Move the staged file to its final key. Never overwrites an existing file."""
    target = content_path(clinic_id, key)
    target.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
    os.link(staged.path, target)  # FileExistsError instead of a silent overwrite
    discard(staged.path)
    return target
